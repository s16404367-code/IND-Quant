#!/usr/bin/env node
/**
 * After `vite build`, copies the built app into ./site/ with STABLE names:
 *   site/app.js, site/app.css, site/version.json
 * These 3 files let the site work even when GitHub Pages is set to "Deploy from a branch"
 * (the root index.html loads them automatically). The GitHub workflow keeps them up to date.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'dist', 'assets');
const site = path.join(root, 'site');
if (!existsSync(assets)) {
  console.error('dist/assets missing — run `vite build` first.');
  process.exit(1);
}
const files = readdirSync(assets);
const js = files.filter((f) => f.endsWith('.js'));
const css = files.filter((f) => f.endsWith('.css'));
if (js.length !== 1 || css.length !== 1) {
  console.error(`Expected exactly 1 JS and 1 CSS bundle, found JS=${js.length} CSS=${css.length}. Code splitting must stay off.`);
  process.exit(1);
}
mkdirSync(site, { recursive: true });
copyFileSync(path.join(assets, js[0]), path.join(site, 'app.js'));
copyFileSync(path.join(assets, css[0]), path.join(site, 'app.css'));
copyFileSync(path.join(root, 'dist', 'version.json'), path.join(site, 'version.json'));
const v = JSON.parse(readFileSync(path.join(site, 'version.json'), 'utf8'));
writeFileSync(path.join(site, 'README.txt'), 'Auto-generated by `npm run build` — do not edit. Used when GitHub Pages is set to "Deploy from a branch".\n');
console.log(`✓ site/ updated (build ${v.buildId})`);
